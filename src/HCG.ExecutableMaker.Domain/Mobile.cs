    public IReadOnlyList<string> Variants =>
        ProductFlavors.Count == 0
            ? BuildTypes
            : [.. ProductFlavors.SelectMany(f => BuildTypes.Select(b => f + char.ToUpperInvariant(b[0]) + b[1..]))];
}

