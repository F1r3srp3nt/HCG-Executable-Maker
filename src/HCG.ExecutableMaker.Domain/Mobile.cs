namespace HCG.ExecutableMaker.Domain;

public enum MobileFramework
{
    /// <summary>Android Gradle project (Java/Kotlin).</summary>
    NativeAndroid,
    /// <summary>Xcode project/workspace.</summary>
    NativeIos,
    Flutter,
    DotNetMaui,
}

/// <summary>What Mobile Build Studio is asked to produce. Each maps to a real toolchain operation.</summary>
public enum MobileOutput
{
    AndroidDebugApk,
    AndroidReleaseApk,
    AndroidAppBundle,
    /// <summary>bundletool build-apks from an existing .aab (an artifact transformation, not a recompilation).</summary>
    AndroidAabToApk,
    IosSimulatorApp,
    IosArchive,
    IosIpa,
}

public enum MobileSigningMode
{
    /// <summary>Use whatever signing the project itself configures (Gradle signingConfig / Xcode settings).</summary>
    ProjectDefault,
    /// <summary>Explicitly unsigned (Android unsigned release, iOS CODE_SIGNING_ALLOWED=NO). Not installable / not exportable.</summary>
    Unsigned,
    /// <summary>A local debug keystore generated by HCG. Never a production key.</summary>
    DebugKeystore,
    /// <summary>Xcode automatic signing for the given development team.</summary>
    AppleAutomatic,
    /// <summary>Xcode manual signing with a named provisioning profile.</summary>
    AppleManual,
}

/// <summary>xcodebuild -exportArchive methods (Xcode 15.3+ names).</summary>
public enum IosExportMethod
{
    AppStoreConnect,
    ReleaseTesting,
    Enterprise,
    Debugging,
}

public enum ApkSetMode
{
    /// <summary>One universal APK containing all ABIs, densities and languages.</summary>
    Universal,
    /// <summary>Split APKs for one device described by a device-spec JSON file.</summary>
    DeviceTargeted,
}

public sealed record AndroidModuleInfo
{
    /// <summary>Module directory relative to the Android project root, '/' separated ("" for single-module roots).</summary>
    public required string Directory { get; init; }
    /// <summary>Gradle project path, e.g. ":app".</summary>
    public required string GradlePath { get; init; }
    public required string BuildFile { get; init; }
    public string? ApplicationId { get; init; }
    public string? Namespace { get; init; }
    public int? MinSdk { get; init; }
    public int? TargetSdk { get; init; }
    public int? CompileSdk { get; init; }
    public int? VersionCode { get; init; }
    public string? VersionName { get; init; }
    public IReadOnlyList<string> BuildTypes { get; init; } = ["debug", "release"];
    public IReadOnlyList<string> ProductFlavors { get; init; } = [];
    public bool HasSigningConfig { get; init; }

    /// <summary>Variant names in Gradle form ("debug", "freeRelease", …).</summary>
    public IReadOnlyList<string> Variants =>
        ProductFlavors.Count == 0
            ? BuildTypes
            : [.. ProductFlavors.SelectMany(f => BuildTypes.Select(b => f + char.ToUpperInvariant(b[0]) + b[1..]))];
}

public sealed record AndroidProjectInfo
{
    /// <summary>Gradle root (directory containing settings.gradle[.kts]) relative to the workspace source, '/' separated.</summary>
    public required string Root { get; init; }
    public string? SettingsFile { get; init; }
    public bool HasWrapper { get; init; }
    public string? WrapperGradleVersion { get; init; }
    public string? AgpVersion { get; init; }
    public bool UsesKotlin { get; init; }
    public IReadOnlyList<AndroidModuleInfo> AppModules { get; init; } = [];
    public IReadOnlyList<string> LibraryModules { get; init; } = [];
}

public sealed record IosSchemeInfo(string Name, string File, bool Shared);

public sealed record IosTargetInfo
{
    public required string Name { get; init; }
    public required string ProductType { get; init; }
    public string? BundleIdentifier { get; init; }
    public string? DeploymentTarget { get; init; }
    public string? DevelopmentTeam { get; init; }
    public string? CodeSignStyle { get; init; }
    public bool IsApplication => ProductType == "com.apple.product-type.application";
}

public sealed record IosProjectInfo
{
    /// <summary>.xcodeproj relative path, if any.</summary>
    public string? ProjectPath { get; init; }
    /// <summary>.xcworkspace relative path, if any (preferred for builds when present, e.g. CocoaPods).</summary>
    public string? WorkspacePath { get; init; }
    public IReadOnlyList<IosSchemeInfo> Schemes { get; init; } = [];
    public IReadOnlyList<IosTargetInfo> Targets { get; init; } = [];
    public IReadOnlyList<string> Configurations { get; init; } = [];
    public bool UsesSwiftPackages { get; init; }
    public bool UsesCocoaPods { get; init; }
    public IEnumerable<IosTargetInfo> AppTargets => Targets.Where(t => t.IsApplication);
}

public sealed record FlutterProjectInfo
{
    public required string Root { get; init; }
    public required string Name { get; init; }
    public string? Version { get; init; }
    public string? SdkConstraint { get; init; }
    public bool HasAndroid { get; init; }
    public bool HasIos { get; init; }
}

public sealed record MauiProjectInfo
{
    public required string ProjectPath { get; init; }
    public string? ApplicationId { get; init; }
    public string? ApplicationTitle { get; init; }
    public string? DisplayVersion { get; init; }
    public IReadOnlyList<string> TargetFrameworks { get; init; } = [];
    public string? AndroidTargetFramework => TargetFrameworks.FirstOrDefault(t => t.Contains("-android", StringComparison.OrdinalIgnoreCase));
    public string? IosTargetFramework => TargetFrameworks.FirstOrDefault(t => t.Contains("-ios", StringComparison.OrdinalIgnoreCase));
}

/// <summary>Static, non-executing analysis of a mobile project.</summary>
public sealed record MobileAnalysis
{
    public required MobileFramework Framework { get; init; }
    public IReadOnlyList<TargetPlatform> Platforms { get; init; } = [];
    public AndroidProjectInfo? Android { get; init; }
    public IosProjectInfo? Ios { get; init; }
    public FlutterProjectInfo? Flutter { get; init; }
    public MauiProjectInfo? Maui { get; init; }
    public IReadOnlyList<string> ApplicationIds { get; init; } = [];
    /// <summary>For imported artifacts (.apk/.aab/.apks/.ipa): the file, relative to the workspace source.</summary>
    public string? ArtifactPath { get; init; }
}

/// <summary>Mobile-specific build settings, persisted with the build record.</summary>
public sealed record MobileBuildOptions
{
    public required MobileFramework Framework { get; init; }
    public required MobileOutput Output { get; init; }
    /// <summary>Android Gradle path of the app module (":app").</summary>
    public string? Module { get; init; }
    /// <summary>Android variant ("debug", "freeRelease") or iOS/MAUI/Flutter configuration ("Debug"/"Release").</summary>
    public string? Variant { get; init; }
    public string? Scheme { get; init; }
    /// <summary>.xcodeproj or .xcworkspace relative path.</summary>
    public string? Container { get; init; }
    public MobileSigningMode Signing { get; init; } = MobileSigningMode.ProjectDefault;
    /// <summary>Apple Developer Team ID (10 characters). Not a secret.</summary>
    public string? DevelopmentTeam { get; init; }
    /// <summary>Provisioning profile name or UUID for manual signing. Not a secret.</summary>
    public string? ProvisioningProfile { get; init; }
    public IosExportMethod? ExportMethod { get; init; }
    /// <summary>
    /// Passes -allowProvisioningUpdates (automatic signing only): Xcode may contact Apple using the account signed in to
    /// Xcode to create or renew profiles. Off unless the user explicitly enables it.
    /// </summary>
    public bool AllowProvisioningUpdates { get; init; }
    public ApkSetMode ApkSetMode { get; init; } = ApkSetMode.Universal;
    /// <summary>Device spec JSON (absolute path) for device-targeted APK sets.</summary>
    public string? DeviceSpecPath { get; init; }
    /// <summary>Input artifact (relative to workspace source) for artifact operations such as AAB→APK.</summary>
    public string? InputArtifact { get; init; }
}

public static class MobileNames
{
    public static string DisplayName(this MobileFramework f) => f switch
    {
        MobileFramework.NativeAndroid => "Android (Gradle)",
        MobileFramework.NativeIos => "iOS (Xcode)",
        MobileFramework.Flutter => "Flutter",
        MobileFramework.DotNetMaui => ".NET MAUI",
        _ => f.ToString(),
    };

    public static string DisplayName(this MobileOutput o) => o switch
    {
        MobileOutput.AndroidDebugApk => "Android Debug APK",
        MobileOutput.AndroidReleaseApk => "Android Release APK",
        MobileOutput.AndroidAppBundle => "Android App Bundle (.aab)",
        MobileOutput.AndroidAabToApk => "AAB → APK (bundletool)",
        MobileOutput.IosSimulatorApp => "iOS Simulator build",
        MobileOutput.IosArchive => "iOS Archive (.xcarchive)",
        MobileOutput.IosIpa => "iOS IPA (export from archive)",
        _ => o.ToString(),
    };

    public static TargetPlatform Platform(this MobileOutput o) => o switch
    {
        MobileOutput.IosSimulatorApp or MobileOutput.IosArchive or MobileOutput.IosIpa => TargetPlatform.IOS,
        _ => TargetPlatform.Android,
    };

    /// <summary>xcodebuild exportOptions "method" value (Xcode 15.3+).</summary>
    public static string XcodeValue(this IosExportMethod m) => m switch
    {
        IosExportMethod.AppStoreConnect => "app-store-connect",
        IosExportMethod.ReleaseTesting => "release-testing",
        IosExportMethod.Enterprise => "enterprise",
        _ => "debugging",
    };
}

/// <summary>Whether an output can be produced for this project on this host, and if not, exactly why.</summary>
public sealed record MobileOutputOption(MobileOutput Output, bool IsAvailable, string Description, string? Reason)
{
    public string DisplayName => Output.DisplayName();
    public TargetPlatform Platform => Output.Platform();
}
