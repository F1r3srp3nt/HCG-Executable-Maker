public sealed record AndroidModuleInfo
{
    /// <summary>Module directory relative to the Android project root, '/' separated ("" for single-module roots).</summary>
    public required string Directory { get; init; }
    /// <summary>Gradle project path, e.g. ":app".</summary>
    public required string GradlePath { get; init; }
    public required string BuildFile { get; init; }
    public string? ApplicationId { get; init; }
    public string? Namespace { get; init; }
    public int? MinSdk { get; init; }
    public int? TargetSdk { get; init; }
    public int? CompileSdk { get; init; }
    public int? VersionCode { get; init; }
    public string? VersionName { get; init; }
    public IReadOnlyList<string> BuildTypes { get; init; } = ["debug", "release"];
    public IReadOnlyList<string> ProductFlavors { get; init; } = [];
    public bool HasSigningConfig { get; init; }

