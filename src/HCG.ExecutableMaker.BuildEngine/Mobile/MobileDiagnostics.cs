using System.Globalization;
using System.Text;
using HCG.ExecutableMaker.Domain;
using HCG.ExecutableMaker.ProjectInspection.Mobile;

namespace HCG.ExecutableMaker.BuildEngine.Mobile;

/// <summary>What is running and what it would build: the inputs of one diagnostics report.</summary>
public sealed record MobileDiagnosticsInput
{
    public required string MakerBuild { get; init; }
    public required string MakerExecutable { get; init; }
    public string? MakerAppBundle { get; init; }
    public required ProjectRecord Project { get; init; }
    public SourceDrift? Drift { get; init; }
    public ToolchainReport? Toolchains { get; init; }
    /// <summary>The saved Mobile Build Studio selection for this project (what the page restores and the build uses).</summary>
    public MobileSelection? Selection { get; init; }
    /// <summary>A build-only minimum iOS the user accepted on the page (not persisted; null from the command line).</summary>
    public string? DeploymentOverride { get; init; }
    /// <summary>The state the page shows right now (null from the command line: computed here the same way).</summary>
    public string? ShownState { get; init; }
    public BuildRecord? LastBuild { get; init; }
    public DateTimeOffset GeneratedAt { get; init; } = DateTimeOffset.UtcNow;
}

/// <summary>
/// A plain-text report of exactly what Mobile Build Studio is working with: the Maker build that runs, where the project was
/// imported from and whether HCG's copy still matches it, the selected Xcode and each SDK's deployment range (read from
/// SDKSettings.json), the selection (project/workspace, scheme, configuration, destination, command) for every iOS output,
/// and every target each scheme builds with its effective deployment target. Generated by the same functions the page and
/// the build use (<see cref="IosBuildSelection"/>, <see cref="MobileCapabilities"/>, <see cref="XcodePlanner"/>,
/// <see cref="MobileBuildState"/>). Contains no credentials: HCG stores none for mobile builds, and signing is reported by
/// mode and identifier only.
/// </summary>
public static class MobileDiagnostics
{
    public static string Create(MobileDiagnosticsInput input)
    {
        var sb = new StringBuilder();
        void L(string s = "") => sb.AppendLine(s);
        string T(DateTimeOffset? t) => t is null ? "never" : t.Value.UtcDateTime.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture) + " UTC";
        var p = input.Project;
        var m = p.Analysis?.Mobile;
        var x = input.Toolchains?.Xcode;

        L("HCG Executable Maker — Mobile Build Studio diagnostics");
        L($"Generated: {T(input.GeneratedAt)}");
        L();
        L("1. MAKER (the application that produced this report)");
        L($"   Build: {input.MakerBuild}");
        L($"   Executable: {input.MakerExecutable}");
        L($"   App bundle: {input.MakerAppBundle ?? "(not running from an .app bundle)"}");
        L();
        L("2. PROJECT");
        L($"   Name: {p.Name}  (id {p.Id})");
        L($"   Imported from: {p.SourceLocation}  ({(p.SourceKind == ProjectSourceKind.ZipArchive ? "ZIP archive" : p.SourceKind.ToString())})");
        L($"   Imported: {T(p.ImportedAt)}; last refreshed from source: {T(p.RefreshedAt)}");
        L($"   Revision HCG copied: {p.SourceRevision ?? "not recorded (imported by a Maker build that did not record it)"}");
        L($"   HCG's copy (what Maker builds): {p.SourceDirectory}");
        L($"     copy at import/refresh: {p.SourceFingerprint ?? "not recorded"}");
        if (input.Drift is { } d)
        {
            L($"     copy now:               {d.SnapshotFingerprint}");
            L($"   Original now: {(d.OriginAvailable ? $"{d.OriginRevision} — {d.OriginFingerprint ?? "(not hashed)"}" : "not available")}");
            L($"   Copy vs original: {d.Describe(25)}");
            if (!d.IsCurrent && d.OriginAvailable) L("   → Maker builds its copy, not the original folder. Use “Refresh from source” to build the original's current files.");
        }
        else L("   Copy vs original: not compared");
        L();

        L("3. XCODE");
        if (x is null) L("   Not detected (no toolchain report).");
        else
        {
            L($"   State: {x.State} — {x.Diagnosis}");
            L($"   Selected for HCG's builds: {x.ActiveDeveloperDirectory ?? "(none)"}  (source: {x.Source switch
            {
                DeveloperDirectorySource.HcgSelection => "chosen in HCG; passed as DEVELOPER_DIR, xcode-select unchanged",
                DeveloperDirectorySource.LaunchEnvironment => "DEVELOPER_DIR from the environment HCG was started in",
                DeveloperDirectorySource.XcodeSelect => "system selection (xcode-select)",
                _ => "none",
            }})");
            L($"   Version: Xcode {x.VerifiedVersion ?? "?"} ({x.VerifiedBuild ?? "?"})");
            Range("iPhoneOS (device)", "iphoneos", "iPhoneOS", x.IosDeploymentRange);
            Range("iPhoneSimulator", "iphonesimulator", "iPhoneSimulator", x.IosSimulatorDeploymentRange);
            L("   Installed Xcodes:");
            foreach (var i in x.Installed)
                L($"     {i.Display}: device iOS {i.IosRange?.Minimum ?? "?"}–{i.IosRange?.Maximum ?? "?"}, Simulator iOS {i.SimulatorRange?.Minimum ?? "?"}–{i.SimulatorRange?.Maximum ?? "?"}" +
                  (i.RangeDiagnostics.Count > 0 ? $" ({string.Join("; ", i.RangeDiagnostics.Select(kv => kv.Key + ": " + kv.Value))})" : ""));
            if (x.Installed.Count == 0) L("     (none found)");
        }
        void Range(string label, string sdk, string platform, IosDeploymentRange? r)
        {
            var file = x?.ActiveDeveloperDirectory is { } dev ? Path.Combine(dev, "Platforms", platform + ".platform", "Developer", "SDKs", platform + ".sdk", "SDKSettings.json") : "?";
            L(r is null
                ? $"   {label} SDK: deployment range not read — {(x!.RangeDiagnostics.TryGetValue(sdk, out var why) ? why : "unknown reason")} ({file})"
                : $"   {label} SDK {r.SdkVersion}: deployment iOS {r.Minimum}–{r.Maximum} (MinimumDeploymentTarget/MaximumDeploymentTarget in {file})");
        }
        L();

        if (m?.Ios is not { } ios || m.ArtifactPath is not null)
        {
            L("4. SELECTION: not an Xcode project (nothing more to report for iOS).");
            return sb.ToString();
        }
        var sel = IosBuildSelection.Restore(p.Id.ToString(), ios, input.Selection);
        L("4. SELECTION (restored exactly as Mobile Build Studio restores it; the build uses the same values)");
        L($"   Saved selection: {(input.Selection is null ? "none (defaults)" : $"container {input.Selection.Container ?? "(default)"}, scheme {input.Selection.Scheme ?? "(default)"}, configuration {input.Selection.Configuration ?? "scheme default"}")}");
        L($"   Project/workspace: {sel.Container}");
        L($"   Scheme: {sel.Scheme}");
        L($"   Configuration: {sel.Configuration ?? "scheme default (Run → Simulator, Archive → device)"}");
        if (input.DeploymentOverride is { } ov) L($"   Build-only minimum iOS accepted on the page: {ov}");
        L($"   Schemes found in the project ({ios.Schemes.Count}):");
        foreach (var s in ios.Schemes)
            L($"     {s.Name}{(s.Shared ? "" : " (user scheme)")}: Run builds {Join(s.RunTargets)} with {s.LaunchConfiguration ?? "?"}; Archive builds {Join(s.ArchiveTargets)} with {s.ArchiveConfiguration ?? "?"}  [{s.File}]");
        L();

        L("5. OUTPUTS for the selection (the command is the build's own: XcodePlanner.Resolve)");
        foreach (var output in new[] { MobileOutput.IosSimulatorApp, MobileOutput.IosArchive, MobileOutput.IosIpa })
        {
            var simulator = output == MobileOutput.IosSimulatorApp;
            var o = new MobileBuildOptions
            {
                Framework = m.Framework, Output = output, Scheme = sel.Scheme, Container = sel.Container,
                Variant = IosBuildSelection.Configuration(ios, sel.Scheme, sel.Configuration, simulator),
                DeploymentTargetOverride = input.DeploymentOverride,
            };
            var option = input.Toolchains is null ? null : MobileCapabilities.Evaluate(m, input.Toolchains, o, sel.Configuration).FirstOrDefault(c => c.Output == output);
            L($"   {output.DisplayName()} — {(option is null ? "not evaluated" : option.IsAvailable ? "available" : "unavailable: " + option.Reason)}");
            L($"     SDK: {IosSchemeCompatibility.SdkFor(simulator)}; configuration: {o.Variant}");
            try { L($"     Command: {XcodePlanner.Preview(o, ios)}"); }
            catch (Exception ex) when (ex is BuildValidationException or InvalidOperationException) { L($"     Command: not planned — {ex.Message}"); }
        }
        L();

        L("6. EFFECTIVE DEPLOYMENT TARGETS (each scheme's own targets and dependencies; test-only targets are not built)");
        foreach (var s in ios.Schemes)
            foreach (var simulator in new[] { false, true })
            {
                var config = IosBuildSelection.Configuration(ios, s.Name, sel.Scheme == s.Name ? sel.Configuration : null, simulator);
                var r = IosSchemeCompatibility.Evaluate(ios, s.Name, config, simulator, x, includeAlternatives: false,
                    deploymentOverride: sel.Scheme == s.Name ? input.DeploymentOverride : null);
                L($"   {s.Name} · {(simulator ? "Simulator" : "device")} · {config}: {r.Fit}{(r.Range is { } range ? $" (SDK accepts iOS {range.Minimum}–{range.Maximum})" : "")}");
                foreach (var t in r.Targets)
                    L($"     {t.Target}{(t.IsDependency ? " (dependency)" : "")}: iOS {t.DeploymentTarget ?? "unresolved"}{(t.Source is null ? "" : " — " + t.Source)}" +
                      (r.Range is { } rr && rr.Contains(t.DeploymentTarget) == false ? "  ← outside the SDK's range" : "") +
                      (t.Unresolved.Count > 0 ? $" (unresolved: {string.Join(", ", t.Unresolved)})" : ""));
            }
        L();

        L("7. STATE");
        var summary = IosBuildSelection.Summarize(ios, sel.Scheme, sel.Configuration, x, input.DeploymentOverride);
        if (summary.CurrentScheme is { } cs) L($"   Current scheme: {cs}");
        if (summary.Problem is { } problem) L($"   Problem: {problem}");
        foreach (var (label, text, _) in summary.Lines) L($"   {label}: {text}");
        foreach (var n in summary.InspectionNotices) L($"   Not verified: {n}");
        if (summary.CompatibleSchemes.Count > 0) L($"   Compatible schemes: {string.Join(", ", summary.CompatibleSchemes.Select(c => $"{c.Scheme} (iOS {c.Minimum ?? "?"})"))}");
        if (summary.KeepRoute is { } keep) L($"   {keep}");
        if (summary.ProjectChange is { } change) L($"   {change}");
        if (input.Toolchains is { } report && p.Analysis is { } analysis)
        {
            var all = MobileCapabilities.Evaluate(m, report, new MobileBuildOptions { Framework = m.Framework, Output = MobileOutput.IosSimulatorApp, Scheme = sel.Scheme, Container = sel.Container, DeploymentTargetOverride = input.DeploymentOverride }, sel.Configuration)
                .Where(o => o.Platform == TargetPlatform.IOS).ToList();
            var state = MobileBuildState.Describe(analysis, m, all, null, null, null, null);
            L($"   State with no output chosen: {state.Tag} — {state.Detail}");
        }
        if (input.ShownState is { } shown) L($"   State shown on the page: {shown}");
        if (input.LastBuild is { } b)
            L($"   Last build: {b.Status} at {T(b.EndedAt ?? b.StartedAt)}" + (b.Provenance is { } prov ? $" — scheme {prov.Scheme}, {prov.Configuration}, {prov.SourceRevision}" : ""));
        return sb.ToString();

        static string Join(IReadOnlyList<string> items) => items.Count == 0 ? "(none)" : string.Join(", ", items);
    }
}
