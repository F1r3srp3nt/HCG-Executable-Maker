    private DesktopConversionOptions CurrentConversionOptions(NodeProjectInfo web)
    {
        var mac = SelectedConversionTarget?.Combination.Platform == TargetPlatform.MacOS || SelectedConversionTarget is null;
        var targets = ConversionFormats.Where(f => f.IsSelected).Select(f => f.Format switch { PackagingFormat.PortableZip => "zip", PackagingFormat.MacDmg => "dmg", _ => null })
            .OfType<string>().ToList();
        return new DesktopConversionOptions(ConversionAppId.Trim(), ConversionAppName.Trim())
        {
            IconPath = ConversionIconPath,
            MacTargets = mac ? (targets.Count == 0 ? ["dir"] : targets) : ["zip", "dmg"],
            MacArchs = [SelectedConversionTarget?.Combination.Platform == TargetPlatform.MacOS && SelectedConversionTarget.Combination.Architecture == TargetArchitecture.X64 ? "x64" : "arm64"],
            MacIdentity = SelectedConversionSigning?.Identity,
            UsePublicEnvironment = ConversionUsePublicEnvironment,
            Source = Project is null ? null : new DesktopConversionSource(Project.Id, Project.Name, Project.SourceLocation, web.Directory),
        };
    }

    private void PlanConversion(bool resetIdentity)
    {
        ConversionError = null;
        ConversionBlockers.Clear(); ConversionWarnings.Clear(); ConversionInfos.Clear(); ConversionChanges.Clear(); ConversionToolchainGaps.Clear();
        var web = SelectedWebProject;
        if (Project is null || web is null)
        {
            ConversionPlan = null;
            FinishConversionRefresh();
            return;
        }
        var root = Project.SourceDirectory;
        var webDir = Path.Combine(root, web.Directory);
        ConversionCategory = web.DesktopEligibility?.Label ?? "";
        DesktopConversionPlan plan;
        try
        {
            DesktopConversionOptions options;
            if (resetIdentity)
            {
                var defaults = WebDesktopConversion.DefaultOptions(web, webDir);
                _settingConversion = true;
                ConversionAppName = defaults.ProductName;
                ConversionAppId = defaults.AppId;
                ConversionIconPath = defaults.IconPath;
                _settingConversion = false;
            }
            options = CurrentConversionOptions(web);
            plan = WebDesktopConversion.Plan(root, web, options);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or HCG.ExecutableMaker.BuildEngine.BuildValidationException)
        {
            _settingConversion = false;
            ConversionPlan = null;
            ConversionTag = new StatusTag("Unreadable", "error");
            ConversionSummary = $"HCG could not read {web.ManifestPath}: {ex.Message}";
            FinishConversionRefresh();
            return;
        }
        ConversionPlan = plan;
        ConversionPreviewStale = false;
        ConversionVersion = web.Version ?? "0.0.0";
        CheckConversionIcon();
        foreach (var f in plan.Findings)
            (f.Level switch { ConversionFindingLevel.Blocker => ConversionBlockers, ConversionFindingLevel.Warning => ConversionWarnings, _ => ConversionInfos })
                .Add(new ConversionFindingItem(f));
        foreach (var c in plan.Changes) ConversionChanges.Add(new ConversionChangeItem(c));
        var (_, omitted, sources, _) = WebDesktopConversion.PublicEnvironment(webDir, true);
        ConversionEnvironmentText = sources.Count == 0
            ? "The project has no .env files: the desktop build uses the app's defaults, like a web build without them."
            : $"Public VITE_ settings from {string.Join(", ", sources)}: {(plan.PublicEnvironment.Count > 0 ? string.Join(", ", plan.PublicEnvironment) : ConversionUsePublicEnvironment ? "none" : "not copied")}." +
              (omitted.Count > 0 ? $" Never copied (look like credentials): {string.Join(", ", omitted)}." : "");

        // Installed toolchains, separately from the project's configuration.
        var report = _toolchains.Latest;
        _conversionNode = null;
        ConversionToolchainText = "";
        if (report is null) ConversionToolchainGaps.Add("Toolchains have not been detected yet. Open the Toolchains page and press Refresh.");
        else
        {
            var installs = report.NodeInstallations ?? [];
            _conversionNode = installs.FirstOrDefault(i => NodeVersionRange.Check(i.Version, web.EnginesNode) == NodeVersionRange.Result.Satisfied
                                                           && NodeVersionRange.Check(i.Version, WebDesktopConversion.ElectronNodeRequirement) == NodeVersionRange.Result.Satisfied);
            if (_conversionNode is null)
                ConversionToolchainGaps.Add(installs.Count == 0
                    ? NodeCapabilities.SelectNode(report, web.EnginesNode).Detail
                    : $"No installed Node.js satisfies both the project ({web.EnginesNode ?? "any version"}) and Electron {WebDesktopConversion.ElectronVersion} ({WebDesktopConversion.ElectronNodeRequirement}). Found: {string.Join(", ", installs.Select(i => $"{i.Version} ({i.Source})"))}. Install Node.js 22.12 or later from {NodeCapabilities.NodeSetupUrl}, then press Refresh on the Toolchains page.");
            else if (_conversionNode.NpmCli is null)
            {
                ConversionToolchainGaps.Add($"npm was not found next to Node.js {_conversionNode.Version} ({_conversionNode.NodePath}). Reinstall Node.js, which includes npm.");
                _conversionNode = null;
            }
            else ConversionToolchainText = $"Uses Node.js {_conversionNode.Version} ({_conversionNode.Source}) with npm {_conversionNode.NpmVersion ?? "(version unknown)"}; it satisfies the project ({web.EnginesNode ?? "no engines field"}) and Electron ({WebDesktopConversion.ElectronNodeRequirement}).";
            if (NodeCapabilities.Combinations(report.Host).Count == 0)
                ConversionToolchainGaps.Add($"HCG packages Electron apps on macOS (.app, zip, dmg) and Linux (app folder) in this version. Packaging on {report.Host.Platform.DisplayName()} is not implemented: open the project in HCG on a Mac to build the macOS app.");
        }

        var category = web.DesktopEligibility?.Category;
        ConversionTag = !plan.CanApply
            ? category == DesktopConversionCategory.ServerDependent ? new StatusTag("Needs a server", "warning") : new StatusTag("Not supported", "error")
            : _conversionNode is null || ConversionTargets.Count == 0 ? new StatusTag("Missing tools", "warning")
            : new StatusTag("Ready to create", "success");
        CanEditConversion = plan.CanApply || plan.Findings.All(f => f.Level != ConversionFindingLevel.Blocker || f.Area is "Identity" or "Icon" or "Signing" or "Targets");
        ConversionSummary = plan.CanApply
            ? plan.Mode == DesktopConversionMode.AddPackaging
                ? $"{plan.ProjectName} is an Electron app without packaging. HCG adds electron-builder configuration and desktop build scripts in a separate copy and keeps your main process."
                : $"{plan.ProjectName} is a Vite + React browser app. HCG creates a separate desktop project that packages its production build ({plan.OutputDirectory}/) in a secured Electron window: the installed app needs no web server, development server, Terminal or Node.js."
            : web.DesktopEligibility is { CanConvert: false } el ? el.Summary
            : $"{plan.ProjectName} cannot be converted with these settings: see below.";
        ConversionDestinationText =
            "Creates a separate desktop project in HCG from a copy; the imported project and the website's own configuration are not changed. node_modules, " +
            $"{plan.OutputDirectory}/, version-control data and .env files are not copied. npm resolves package-lock.json with --ignore-scripts: no project or package script runs until you start the build (after confirming that you trust the project).";
        FinishConversionRefresh();
    }

    private async Task FindExistingDesktopProjectAsync()
    {
        _existingDesktopProject = null;
        ConversionExistingProjectText = "";
        var web = SelectedWebProject;
        if (Project is null || web is null) return;
        foreach (var p in await _projects.ListAsync())
        {
            var record = Path.Combine(p.SourceDirectory, WebDesktopConversion.RecordFile.Replace('/', Path.DirectorySeparatorChar));
            if (p.Id == Project.Id || !File.Exists(record)) continue;
            if (WebDesktopConversion.ReadRecord(record, out _) is { Source: { } s } r && s.ProjectId == Project.Id && s.WebDirectory == web.Directory)
            {
                _existingDesktopProject = p;
                ConversionExistingProjectText = $"A desktop project was created from this web app on {r.CreatedAt.ToLocalTime():yyyy-MM-dd HH:mm} (“{p.Name}”). Creating again updates that project — its generated files are replaced and its build history is kept — instead of adding another one.";
                return;
            }
        }
    }

    private void FinishConversionRefresh()
    {
        HasConversionBlockers = ConversionBlockers.Count > 0;
        HasConversionWarnings = ConversionWarnings.Count > 0;
        HasConversionToolchainGaps = ConversionToolchainGaps.Count > 0;
        CreateDesktopWorkspaceCommand.NotifyCanExecuteChanged();
    }

    private bool CanCreateDesktopWorkspace() =>
        ConversionPlan is not null && CanEditConversion && _conversionNode is not null && !IsConverting && Project is not null && ConversionTargets.Count > 0
        && !ConversionIconInvalid && ConversionOutputDirectory.Trim().Length > 0;

    [RelayCommand(CanExecute = nameof(CanCreateDesktopWorkspace))]
    private async Task CreateDesktopWorkspaceAsync()
    {
        // Always plan again with the options as they are now: what is written is exactly what was checked.
        PlanConversion(resetIdentity: false);
        if (ConversionPlan is not { CanApply: true } plan || _conversionNode is null)
        {
            ConversionError = "Resolve the items under “Project configuration” first; nothing was written.";
            return;
        }
        var node = _conversionNode;
        var sourceRoot = Project!.SourceDirectory;
        var original = Project.Name;
        var target = SelectedConversionTarget!.Combination;
        var formats = ConversionFormats.Where(f => f.IsSelected).Select(f => f.Format).ToList();
        var output = ConversionOutputDirectory.Trim();
        // Written outside HCG's data folder (the importer refuses that), then imported (or swapped in) and removed.
        var stagingRoot = Path.Combine(Path.GetTempPath(), "hcg-desktop-" + Guid.NewGuid().ToString("N")[..12]);
        var staging = Path.Combine(stagingRoot, Slug(plan.Options.ProductName) + "-desktop");
        IsConverting = true;
        ConversionError = null;
        ConversionLog.Clear();
        HasConversionLog = false;
        ConversionStatus = "Generating the desktop project…";
        _conversionCts = new CancellationTokenSource();
        var ct = _conversionCts.Token;
        try
        {
            var env = BuildEnvironmentPolicy.CreateUntrustedBuildEnvironment().Environment;
            var result = await Task.Run(() => WebDesktopConversion.ApplyAsync(plan, sourceRoot, staging, node, _processRunner, env,
                line => Dispatcher.UIThread.Post(() => { ConversionLog.Add(SecretRedactor.Redact(line)); HasConversionLog = true; ConversionStatus = line.Trim(); }), ct), ct);
            if (!result.Success)
            {
                ConversionError = result.Error;
                ConversionStatus = "";
                return;
            }
            ProjectRecord desktop;
            if (_existingDesktopProject is { } existing && Directory.Exists(existing.WorkspacePath))
            {
                ConversionStatus = $"Updating the existing desktop project “{existing.Name}”…";
                await Task.Run(() => _projectService.ReplaceSourceAsync(existing, staging, ct), ct);
                desktop = existing;
            }
            else
            {
                ConversionStatus = "Importing the desktop project…";
                desktop = (await Task.Run(() => _projectService.ImportDirectoryAsync(staging, null, ct), ct)).Project;
            }
            var changed = string.Join(", ", plan.Changes.Where(c => c.Kind != WorkspaceChangeKind.Remove).Select(c => c.RelativePath));
            await OpenDesktopProjectForBuildAsync(desktop, target, formats, output,
                $"Desktop project {(_existingDesktopProject is null ? "created" : "updated")} from “{original}” ({(plan.ProjectDirectory.Length == 0 ? "root" : plan.ProjectDirectory)}), which is unchanged. Generated: {changed}. " +
                "Review the summary, confirm that you trust the project, then start the build: install dependencies → compile the web app → package → verify.");
        }
        catch (OperationCanceledException) { ConversionError = "Cancelled. Nothing was imported and the partial desktop project was removed."; }
        catch (Exception ex) { ConversionError = "The desktop project could not be created: " + SecretRedactor.Redact(ex.Message); }
        finally
        {
            IsConverting = false;
            ConversionStatus = "";
            _conversionCts?.Dispose();
            _conversionCts = null;
            try { if (Directory.Exists(stagingRoot)) Directory.Delete(stagingRoot, recursive: true); } catch (IOException) { } catch (UnauthorizedAccessException) { }
            await LoadRecentProjectsAsync();
        }
    }

    /// <summary>Opens the generated desktop project at the Build step with the target, formats and output folder chosen above.</summary>
    private async Task OpenDesktopProjectForBuildAsync(ProjectRecord desktop, NodeCapabilities.Combination target, IReadOnlyList<PackagingFormat> formats, string output, string notice)
    {
        Project = desktop;
        ApplyAnalysis(desktop.Analysis ?? await _projectService.InspectAsync(desktop, CancellationToken.None));
        if (!IsElectronBuild)
        {
            DesktopWorkspaceNotice = notice + " The desktop project could not be opened for building automatically: choose it under Project to build.";
            Step = WizardStep.Inspect;
            UpdateSteps();
            return;
        }
        await PrepareConfigurationAsync();
        SelectedPlatform = PlatformOptions.FirstOrDefault(p => p.Value == target.Platform && p.IsEnabled) ?? SelectedPlatform;
        SelectedArchitecture = ArchitectureOptions.FirstOrDefault(a => a.Value == target.Architecture) ?? SelectedArchitecture;
        OutputDirectory = output;
        PreparePackaging(formats);
        PrepareSummary();
        TrustAcknowledged = false;
        DesktopWorkspaceNotice = notice;
        Step = HasConfigErrors ? WizardStep.Configure : WizardStep.Build;
        UpdateSteps();
    }

    [RelayCommand] private void CancelDesktopConversion() => _conversionCts?.Cancel();

    /// <summary>Missing toolchains are installed or selected on the Toolchains page (HCG never installs them itself).</summary>
    [RelayCommand] private void OpenToolchainsPage() => _navigation.Navigate("toolchains");

    private void ResetDesktopConversion()
    {
        DesktopWorkspaceNotice = null;
        ConversionError = null;
        ConversionLog.Clear();
        HasConversionLog = false;
        ConversionStatus = "";
        ConversionPlan = null;
        _existingDesktopProject = null;
        ConversionExistingProjectText = "";
    }

    private static string Slug(string name)
    {
        var s = System.Text.RegularExpressions.Regex.Replace(name.ToLowerInvariant(), "[^a-z0-9]+", "-").Trim('-');
        return s.Length == 0 ? "app" : s.Length > 48 ? s[..48].TrimEnd('-') : s;
    }
