    /// <summary>Targets, formats, output folder and signing choices for this host (only what HCG can really build here).</summary>
    private void PrepareConversionChoices()
    {
        _settingConversion = true;
        try
        {
            ConversionTargets.Clear();
            foreach (var c in NodeCapabilities.Combinations(HostInfo.Detect()))
                ConversionTargets.Add(new ConversionTargetChoice(c, c.Platform == TargetPlatform.MacOS
                    ? $"macOS · {(c.Architecture == TargetArchitecture.Arm64 ? "Apple silicon (arm64)" : "Intel (x64)")}"
                    : $"{c.Platform.DisplayName()} · {c.Architecture.DisplayName()} (unpacked app folder)"));
            SelectedConversionTarget = ConversionTargets.FirstOrDefault(t => t.Combination.Architecture == HostInfo.CurrentArchitecture) ?? ConversionTargets.FirstOrDefault();
            RefreshConversionFormats();
            if (ConversionOutputDirectory.Length == 0) ConversionOutputDirectory = _paths.DefaultOutputDirectory;
            if (ConversionSigningChoices.Count == 0) ConversionSigningChoices.Add(new ConversionSigningChoice(null, "Ad-hoc (this Mac only — not signed for distribution)"));
            SelectedConversionSigning ??= ConversionSigningChoices[0];
            DescribeConversionSigning();
        }
        finally { _settingConversion = false; }
        _ = LoadDefaultOutputAsync();
    }

    private async Task LoadDefaultOutputAsync()
    {
        var settings = await _settings.LoadAsync();
        if (settings.DefaultOutputDirectory is { Length: > 0 } d && ConversionOutputDirectory == _paths.DefaultOutputDirectory) ConversionOutputDirectory = d;
    }

    private void RefreshConversionFormats()
    {
        var keep = ConversionFormats.Where(f => !f.IsSelected).Select(f => f.Format).ToHashSet();
        ConversionFormats.Clear();
        foreach (var f in SelectedConversionTarget?.Combination.Formats ?? [])
        {
            var required = f is PackagingFormat.MacAppBundle or PackagingFormat.PortableFolder;
            ConversionFormats.Add(new ConversionFormatItem(f, f switch
            {
                PackagingFormat.MacAppBundle => "macOS app (.app) — always built",
                PackagingFormat.PortableZip => "ZIP archive of the .app",
                PackagingFormat.MacDmg => "DMG disk image",
                PackagingFormat.PortableFolder => "Unpacked app folder (Linux) — always built",
                _ => f.DisplayName(),
            }, required) { IsSelected = required || !keep.Contains(f) });
        }
        foreach (var item in ConversionFormats) item.PropertyChanged += (_, _) => MarkPreviewStale();
    }

    private async Task LoadConversionSigningAsync()
    {
        if (_signing is null) await RefreshSigningAsync();
        var identities = _signing?.OfKind(AppleCertificateKind.DeveloperIdApplication) ?? [];
        var keep = SelectedConversionSigning?.Identity;
        _settingConversion = true;
        try
        {
            ConversionSigningChoices.Clear();
            ConversionSigningChoices.Add(new ConversionSigningChoice(null, "Ad-hoc (this Mac only — not signed for distribution)"));
            foreach (var i in identities)
            {
                var name = i.Name.StartsWith("Developer ID Application: ", StringComparison.Ordinal) ? i.Name["Developer ID Application: ".Length..] : i.Name;
                ConversionSigningChoices.Add(new ConversionSigningChoice(name, $"Developer ID Application: {name}"));
            }
            SelectedConversionSigning = ConversionSigningChoices.FirstOrDefault(c => c.Identity == keep) ?? ConversionSigningChoices[0];
            DescribeConversionSigning();
        }
        finally { _settingConversion = false; }
    }

    private void DescribeConversionSigning()
    {
        var developerIds = ConversionSigningChoices.Count(c => c.Identity is not null);
        if (HostInfo.CurrentPlatform != TargetPlatform.MacOS)
        {
            ConversionSigningStatus = "Not applicable on this computer: the Linux app folder is not code-signed. macOS signing happens when the app is built on a Mac.";
            ConversionNotarizationStatus = "Not applicable (macOS only).";
            return;
        }
        ConversionSigningStatus = SelectedConversionSigning?.Identity is { } id
            ? $"Signed by electron-builder with “Developer ID Application: {id}” (hardened runtime). Requires that certificate and its private key in your login keychain; macOS may ask to allow access to it."
            : "Ad-hoc signature: the app runs on this Mac and is labelled UNSIGNED for distribution. Other Macs show a Gatekeeper warning. " +
              (developerIds == 0 ? "No Developer ID Application certificate was found in your keychains; distribution needs one (Apple Developer Program)." : $"{developerIds} Developer ID Application identit{(developerIds == 1 ? "y is" : "ies are")} available above.");
        ConversionNotarizationStatus = "Not run. Notarization is a separate, explicit step after a Developer ID signed build (xcrun notarytool submit … --wait, then xcrun stapler staple). HCG does not notarize Electron apps automatically in this version.";
    }

