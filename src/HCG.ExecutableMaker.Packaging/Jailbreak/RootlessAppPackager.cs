using System.Formats.Tar;
using System.IO.Compression;
using System.Text;
using System.Text.RegularExpressions;
using HCG.ExecutableMaker.Core;
using HCG.ExecutableMaker.Packaging.Mobile;

namespace HCG.ExecutableMaker.Packaging.Jailbreak;

/// <summary>What the package must be. Identity, version and texts come from the person packaging, never guessed.</summary>
public sealed record RootlessAppPackageSpec(
    string PackageId,
    string Version,
    string Name,
    string Maintainer,
    string Description,
    string Section = "Applications",
    string? Author = null,
    string? Homepage = null,
    string? Depiction = null,
    IReadOnlyList<string>? ExtraDepends = null,
    string? EntitlementsFile = null,
    DateTimeOffset? Timestamp = null);

/// <summary>
/// Turns an iOS app that a build already produced (a device .app) into a rootless jailbreak application package
/// (<c>iphoneos-arm64</c>, files only under <c>/var/jb/Applications/&lt;Name&gt;.app</c>), in HCG Repo's documented
/// form: gzip members, <c>Depends: firmware (&gt;= MinimumOS), uikittools</c>, and postinst/postrm that only register or
/// unregister the app with <c>uicache</c>. Unsigned Mach-O files are pseudo-signed with ldid, with the project's own
/// entitlements file if one is given; HCG never adds entitlements and refuses privileged ones.
/// The app's code and capabilities are not changed. Nothing is installed.
/// </summary>
public static partial class RootlessAppPackager
{
    public const string Prefix = "var/jb";
    public const string Architecture = "iphoneos-arm64";
    /// <summary>The Maintainer/Author HCG's published packages use (HCG Repo pool, e.g. com.hakmicapitalgroup.hcgnexus).</summary>
    public const string HcgMaintainer = "Hakmi Capital Group";

    /// <summary>Entitlements that grant powers beyond an ordinary app's sandbox. Packaging refuses them.</summary>
    public static readonly string[] PrivilegedEntitlementKeys =
    [
        "platform-application", "com.apple.private.security.no-sandbox", "com.apple.private.security.container-required",
        "com.apple.private.skip-library-validation", "com.apple.security.cs.disable-library-validation", "task_for_pid-allow",
        "get-task-allow-all", "com.apple.system-task-ports", "com.apple.private.persona-mgmt", "com.apple.private.security.storage.AppDataContainers",
        "com.apple.private.MobileContainerManager.allowed", "com.apple.springboard.launchapplications", "run-unsigned-code",
        "dynamic-codesigning", "com.apple.private.amfi.can-load-cdhash", "com.apple.rootless.install", "com.apple.rootless.install.heritable",
    ];

    public sealed record Result(string DebPath, string ControlText, IReadOnlyList<string> SignedFiles, IReadOnlyList<string> Log);

    public static string AppInstallPath(IosAppBundle app) => $"/{Prefix}/Applications/{app.AppDirectoryName}";

    public static string ControlText(RootlessAppPackageSpec spec, IosAppBundle app, long installedSizeKiB)
    {
        var depends = new List<string>();
        if (app.MinimumOS is { Length: > 0 } min) depends.Add($"firmware (>= {min})");
        depends.Add("uikittools");
        foreach (var d in spec.ExtraDepends ?? []) if (!depends.Contains(d)) depends.Add(d);
        var sb = new StringBuilder();
        sb.Append("Package: ").Append(spec.PackageId).Append('\n');
        sb.Append("Name: ").Append(spec.Name).Append('\n');
        sb.Append("Version: ").Append(spec.Version).Append('\n');
        sb.Append("Architecture: ").Append(Architecture).Append('\n');
        sb.Append("Maintainer: ").Append(spec.Maintainer).Append('\n');
        sb.Append("Author: ").Append(spec.Author ?? spec.Maintainer).Append('\n');
        sb.Append("Section: ").Append(spec.Section).Append('\n');
        sb.Append("Depends: ").Append(string.Join(", ", depends)).Append('\n');
        sb.Append("Installed-Size: ").Append(installedSizeKiB).Append('\n');
        if (spec.Homepage is { Length: > 0 } h) sb.Append("Homepage: ").Append(h).Append('\n');
        if (spec.Depiction is { Length: > 0 } dep) sb.Append("Depiction: ").Append(dep).Append('\n');
        var lines = spec.Description.Replace("\r", "").Split('\n');
        sb.Append("Description: ").Append(lines[0]).Append('\n');
        foreach (var l in lines.Skip(1)) sb.Append(' ').Append(l.Length == 0 ? "." : l).Append('\n');
        return sb.ToString();
    }

    /// <summary>The two maintainer scripts: register on configure, unregister on remove/purge. Nothing else.</summary>
    public static (string PostInst, string PostRm) Scripts(IosAppBundle app)
    {
        var path = AppInstallPath(app);
        var postinst = $"""
            #!/bin/sh
            # Generated by HCG Executable Maker: registers {app.AppDirectoryName} with the home screen (HCG Repo convention).
            if [ "$1" = "configure" ]; then
              uicache -p "{path}" || echo "HCG: uicache could not register {path}; run: uicache -p {path}" >&2
            fi
            exit 0

            """;
        var postrm = $"""
            #!/bin/sh
            # Generated by HCG Executable Maker: removes {app.AppDirectoryName} from the home screen when the package is removed.
            if [ "$1" = "remove" ] || [ "$1" = "purge" ]; then
              uicache -u "{path}" || echo "HCG: uicache could not unregister {path}; run: uicache -u {path}" >&2
            fi
            exit 0

            """;
        return (postinst.Replace("\r", ""), postrm.Replace("\r", ""));
    }

    [GeneratedRegex(@"^[a-z0-9][a-z0-9.+-]+$")] public static partial Regex PackageIdRegex();
    [GeneratedRegex(@"^(\d+:)?[0-9][A-Za-z0-9.+~-]*$")] public static partial Regex VersionRegex();

    /// <summary>Problems with the request itself (before anything is built).</summary>
    public static IReadOnlyList<string> CheckSpec(RootlessAppPackageSpec spec, IosAppBundle app)
    {
        var problems = new List<string>(app.Problems);
        if (!PackageIdRegex().IsMatch(spec.PackageId)) problems.Add($"Package ID \"{spec.PackageId}\" is not a valid Debian package name (lower-case letters, digits, '.', '+', '-').");
        if (!VersionRegex().IsMatch(spec.Version)) problems.Add($"Version \"{spec.Version}\" is not a valid Debian version (e.g. 1.0.0~beta1).");
        if (string.IsNullOrWhiteSpace(spec.Name)) problems.Add("A display name is required.");
        if (string.IsNullOrWhiteSpace(spec.Maintainer)) problems.Add("A maintainer is required (HCG packages use \"Hakmi Capital Group\").");
        if (string.IsNullOrWhiteSpace(spec.Description)) problems.Add("A description is required.");
        if (spec.EntitlementsFile is { } ent)
        {
            if (!File.Exists(ent)) problems.Add($"The entitlements file {ent} does not exist.");
            else
            {
                try
                {
                    var keys = PlistReader.ParseDictionary(File.ReadAllBytes(ent)).Keys;
                    var privileged = keys.Where(k => PrivilegedEntitlementKeys.Contains(k) || k.StartsWith("com.apple.private.", StringComparison.Ordinal)).ToList();
                    if (privileged.Count > 0)
                        problems.Add($"The entitlements file asks for privileged entitlements ({string.Join(", ", privileged)}). HCG packages apps with their ordinary capabilities only; these need a separate, reviewed decision.");
                }
                catch (Exception ex) when (ex is FormatException or InvalidDataException or InvalidCastException) { problems.Add($"The entitlements file cannot be read: {ex.Message}"); }
            }
        }
        foreach (var b in app.Binaries)
            foreach (var s in b.Slices)
            {
                if (s.Platform == "iOS Simulator") problems.Add($"{b.RelativePath} is built for the iOS Simulator; only device builds can be packaged.");
                else if (s.Platform is not null and not "iOS") problems.Add($"{b.RelativePath} ({s.Architecture}) is built for {s.Platform}, not iOS.");
                if (s.Encrypted) problems.Add($"{b.RelativePath} is encrypted (an App Store binary); it cannot be repackaged.");
            }
        if (app.Main is { } main && !main.Slices.Any(s => s.Architecture is "arm64" or "arm64e"))
            problems.Add($"The main executable has no arm64 slice ({string.Join(", ", main.Slices.Select(s => s.Architecture))}); rootless iphoneos-arm64 needs one.");
        return problems;
    }

    /// <summary>
    /// Builds the package into <paramref name="outputDir"/>: stages a copy of the app, pseudo-signs unsigned Mach-O
    /// files with ldid when needed, writes control.tar.gz and data.tar.gz, and assembles the .deb.
    /// </summary>
    public static async Task<Result> PackageAsync(IosAppBundle app, RootlessAppPackageSpec spec, string outputDir, string? ldidPath, IProcessRunner runner, Action<string>? log, CancellationToken ct)
    {
        var lines = new List<string>();
        void Log(string m) { lines.Add(m); log?.Invoke(m); }
        var problems = CheckSpec(spec, app);
        if (problems.Count > 0) throw new InvalidOperationException("Cannot package: " + string.Join(" ", problems));

        Directory.CreateDirectory(outputDir);
        var stage = Path.Combine(outputDir, ".stage-" + Guid.NewGuid().ToString("N")[..8]);
        var appStage = Path.Combine(stage, Prefix, "Applications", app.AppDirectoryName);
        try
        {
            Log($"Staging {app.AppDirectoryName} at {AppInstallPath(app)} (a copy; the build output is not changed)");
            CopyTree(app.AppPath, appStage);

            // Sign what is unsigned: nested code first (deepest first), the main executable last.
            var signed = new List<string>();
            var unsigned = app.Binaries.Where(b => b.Slices.Count > 0 && b.Slices.Any(s => !s.HasCodeSignature)).Select(b => b.RelativePath)
                .OrderByDescending(p => p.Count(c => c == '/')).ThenBy(p => p == app.Executable ? 1 : 0).ThenBy(p => p, StringComparer.Ordinal).ToList();
            if (unsigned.Count > 0)
            {
                if (ldidPath is null)
                    throw new InvalidOperationException($"{unsigned.Count} Mach-O file(s) are unsigned ({string.Join(", ", unsigned.Take(5))}) and ldid was not found. Install ldid (macOS: brew install ldid) and run again.");
                foreach (var rel in unsigned)
                {
                    var file = Path.Combine(appStage, rel);
                    var args = new List<string> { rel == app.Executable && spec.EntitlementsFile is { } ent ? "-S" + Path.GetFullPath(ent) : "-S", file };
                    var output = new StringBuilder();
                    var r = await runner.RunAsync(new ProcessSpec { Executable = ldidPath, Arguments = args, Timeout = TimeSpan.FromMinutes(2) },
                        (_, line) => { lock (output) output.AppendLine(line); }, ct).ConfigureAwait(false);
                    if (!r.Succeeded)
                        throw new InvalidOperationException($"ldid could not sign {rel} (exit {r.ExitCode}{(r.TimedOut ? ", timed out" : "")}): {output.ToString().Trim()}");
                    signed.Add(rel);
                    Log($"Pseudo-signed {rel} with ldid{(rel == app.Executable && spec.EntitlementsFile is not null ? " (the project's entitlements file)" : " (no entitlements)")}");
                }
            }
            else Log("Every Mach-O already carries a code signature; signatures are kept as built.");

            var installedKiB = (Directory.EnumerateFiles(stage, "*", SearchOption.AllDirectories).Sum(f => new FileInfo(f).Length) + 1023) / 1024;
            var control = ControlText(spec, app, installedKiB);
            var (postinst, postrm) = Scripts(app);
            var time = spec.Timestamp ?? DateTimeOffset.UnixEpoch;

            var controlTar = TarGz(w =>
            {
                Dir(w, "./", time);
                FileEntry(w, "./control", Encoding.UTF8.GetBytes(control), Mode644, time);
                FileEntry(w, "./postinst", Encoding.UTF8.GetBytes(postinst), Mode755, time);
                FileEntry(w, "./postrm", Encoding.UTF8.GetBytes(postrm), Mode755, time);
            });
            var dataTar = TarGz(w =>
            {
                Dir(w, "./", time);
                foreach (var d in new[] { "./var/", "./var/jb/", "./var/jb/Applications/" }) Dir(w, d, time);
                AddTree(w, stage, Path.Combine(stage, Prefix, "Applications", app.AppDirectoryName), time);
            });
            var debName = $"{spec.PackageId}_{spec.Version.Replace(':', '_')}_{Architecture}.deb";
            var debPath = Path.Combine(outputDir, debName);
            WriteAr(debPath, time, ("debian-binary", "2.0\n"u8.ToArray()), ("control.tar.gz", controlTar), ("data.tar.gz", dataTar));
            Log($"Wrote {debName}: control.tar.gz {controlTar.Length:N0} bytes, data.tar.gz {dataTar.Length:N0} bytes (gzip)");
            return new Result(debPath, control, signed, lines);
        }
        finally
        {
            try { Directory.Delete(stage, recursive: true); } catch (IOException) { } catch (UnauthorizedAccessException) { }
        }
    }

    private const UnixFileMode Mode644 = UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.GroupRead | UnixFileMode.OtherRead;
    private const UnixFileMode Mode755 = Mode644 | UnixFileMode.UserExecute | UnixFileMode.GroupExecute | UnixFileMode.OtherExecute;

    private static void CopyTree(string from, string to)
    {
        Directory.CreateDirectory(to);
        foreach (var dir in Directory.EnumerateDirectories(from, "*", SearchOption.AllDirectories))
            Directory.CreateDirectory(Path.Combine(to, Path.GetRelativePath(from, dir)));
        foreach (var file in Directory.EnumerateFiles(from, "*", SearchOption.AllDirectories))
        {
            var dest = Path.Combine(to, Path.GetRelativePath(from, file));
            if (new FileInfo(file).LinkTarget is { } link) { File.CreateSymbolicLink(dest, link); continue; }
            File.Copy(file, dest, overwrite: true);
        }
    }

    private static byte[] TarGz(Action<TarWriter> write)
    {
        using var ms = new MemoryStream();
        using (var gz = new GZipStream(ms, CompressionLevel.SmallestSize, leaveOpen: true))
        using (var tar = new TarWriter(gz, TarEntryFormat.Gnu, leaveOpen: true))
            write(tar);
        return ms.ToArray();
    }

    private static void Dir(TarWriter w, string name, DateTimeOffset time) =>
        w.WriteEntry(new GnuTarEntry(TarEntryType.Directory, name) { Mode = Mode755, ModificationTime = time, Uid = 0, Gid = 0, UserName = "root", GroupName = "wheel" });

    private static void FileEntry(TarWriter w, string name, byte[] data, UnixFileMode mode, DateTimeOffset time) =>
        w.WriteEntry(new GnuTarEntry(TarEntryType.RegularFile, name)
        {
            Mode = mode, ModificationTime = time, Uid = 0, Gid = 0, UserName = "root", GroupName = "wheel", DataStream = new MemoryStream(data),
        });

    /// <summary>The app's files, sorted, with modes from the build (executables 0755, everything else 0644).</summary>
    private static void AddTree(TarWriter w, string root, string dir, DateTimeOffset time)
    {
        Dir(w, "./" + Path.GetRelativePath(root, dir).Replace('\\', '/') + "/", time);
        foreach (var entry in Directory.EnumerateFileSystemEntries(dir).Order(StringComparer.Ordinal))
        {
            var rel = "./" + Path.GetRelativePath(root, entry).Replace('\\', '/');
            var info = new FileInfo(entry);
            if (info.LinkTarget is { } link)
            {
                w.WriteEntry(new GnuTarEntry(TarEntryType.SymbolicLink, rel) { LinkName = link, Mode = Mode755, ModificationTime = time, Uid = 0, Gid = 0, UserName = "root", GroupName = "wheel" });
                continue;
            }
            if (Directory.Exists(entry)) { AddTree(w, root, entry, time); continue; }
            var executable = MachOLinkage.IsMachO(entry) || (!OperatingSystem.IsWindows() && (File.GetUnixFileMode(entry) & UnixFileMode.UserExecute) != 0);
            using var data = File.OpenRead(entry);
            w.WriteEntry(new GnuTarEntry(TarEntryType.RegularFile, rel)
            {
                Mode = executable ? Mode755 : Mode644, ModificationTime = time, Uid = 0, Gid = 0, UserName = "root", GroupName = "wheel", DataStream = data,
            });
        }
    }

    private static void WriteAr(string path, DateTimeOffset time, params (string Name, byte[] Data)[] members)
    {
        using var fs = File.Create(path);
        fs.Write("!<arch>\n"u8);
        foreach (var (name, data) in members)
        {
            var header = $"{name,-16}{time.ToUnixTimeSeconds(),-12}{0,-6}{0,-6}{"100644",-8}{data.Length,-10}`\n";
            fs.Write(Encoding.ASCII.GetBytes(header));
            fs.Write(data);
            if (data.Length % 2 == 1) fs.WriteByte((byte)'\n');
        }
    }
}
