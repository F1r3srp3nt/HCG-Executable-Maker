using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using HCG.ExecutableMaker.Core;
using HCG.ExecutableMaker.Domain;

namespace HCG.ExecutableMaker.Packaging.Packagers;

/// <summary>
/// Generates the Inno Setup 6 script for a Windows Setup.exe. All values that come from the project or the user are
/// escaped for Inno's syntax (<c>{</c> starts a constant, <c>"</c> delimits parameters); control characters are removed.
/// The script contains no [Code] section, so nothing user-controlled is ever compiled as Pascal script.
/// </summary>
public static partial class InnoSetupScript
{
    public sealed record Input
    {
        public required BuildSettings Settings { get; init; }
        /// <summary>Absolute path of the self-contained publish folder to bundle.</summary>
        public required string SourceDirectory { get; init; }
        /// <summary>File name of the application's .exe inside <see cref="SourceDirectory"/>.</summary>
        public required string ExecutableFileName { get; init; }
        public required string OutputDirectory { get; init; }
        public required string OutputBaseFileName { get; init; }
        public string? SetupIconPath { get; init; }
        /// <summary>Inno Setup version (e.g. 6.4.3). Architecture identifiers changed in 6.3.</summary>
        public Version? CompilerVersion { get; init; }
    }

    /// <summary>
    /// Stable installer identity derived from the reverse-DNS application ID, so a newer version of the same app
    /// upgrades the existing installation instead of installing side by side.
    /// </summary>
    public static Guid AppId(string applicationId)
    {
        var hash = SHA256.HashData(Encoding.UTF8.GetBytes("hcg-executable-maker/windows-installer/" + applicationId.Trim().ToLowerInvariant()));
        var bytes = hash.AsSpan(0, 16).ToArray();
        bytes[7] = (byte)((bytes[7] & 0x0F) | 0x50); // version 5-style (name-based)
        bytes[8] = (byte)((bytes[8] & 0x3F) | 0x80); // RFC 4122 variant
        return new Guid(bytes);
    }

    public static string Generate(Input input)
    {
        var s = input.Settings;
        var o = s.WindowsInstaller;
        if (s.Platform != TargetPlatform.Windows) throw new InvalidOperationException("A Windows installer requires a Windows target.");
        if (!input.ExecutableFileName.EndsWith(".exe", StringComparison.OrdinalIgnoreCase) || input.ExecutableFileName.IndexOfAny(['\\', '/', ':', '"']) >= 0)
            throw new InvalidOperationException($"'{input.ExecutableFileName}' is not a valid Windows executable file name.");

        var name = Clean(s.Identity.ApplicationName, "Application");
        var publisher = Clean(s.Identity.Publisher, "");
        var version = Clean(s.Identity.Version, "1.0.0");
        var folder = PathGuard.SanitizeFileName(string.IsNullOrWhiteSpace(o.InstallFolderName) ? name : o.InstallFolderName, "Application");
        var shortcut = PathGuard.SanitizeFileName(name, "Application");
        var modern = input.CompilerVersion is null || input.CompilerVersion >= new Version(6, 3);
        var arch = s.Architecture switch
        {
            TargetArchitecture.X64 => modern ? "x64compatible" : "x64",
            TargetArchitecture.Arm64 => "arm64",
            _ => throw new InvalidOperationException($"Unsupported installer architecture {s.Architecture}."),
        };

        var sb = new StringBuilder();
        sb.AppendLine($"; Generated by HCG Executable Maker {HostInfo.ProductVersion}. Regenerated on every build — do not edit.");
        sb.AppendLine("[Setup]");
        Directive("AppId", "{{" + AppId(s.Identity.ApplicationId).ToString("D").ToUpperInvariant() + "}");
        Directive("AppName", Inno(name));
        Directive("AppVersion", Inno(version));
        Directive("AppVerName", Inno($"{name} {version}"));
        if (publisher.Length > 0) Directive("AppPublisher", Inno(publisher));
        if (NumericVersion(version) is { } numeric) Directive("VersionInfoVersion", numeric);
        Directive("VersionInfoDescription", Inno($"{name} Setup"));
        Directive("DefaultDirName", "{autopf}\\" + Inno(folder));
        Directive("DisableProgramGroupPage", "yes");
        Directive("UninstallDisplayName", Inno(name));
        Directive("UninstallDisplayIcon", "{app}\\" + Inno(input.ExecutableFileName));
        Directive("OutputDir", Inno(input.OutputDirectory));
        Directive("OutputBaseFilename", Inno(input.OutputBaseFileName));
        if (input.SetupIconPath is not null) Directive("SetupIconFile", Inno(input.SetupIconPath));
        Directive("Compression", "lzma2");
        Directive("SolidCompression", "yes");
        Directive("WizardStyle", "modern");
        Directive("PrivilegesRequired", o.Scope == InstallScope.AllUsers ? "admin" : "lowest");
        Directive("ArchitecturesAllowed", arch);
        Directive("ArchitecturesInstallIn64BitMode", arch);
        Directive("SetupLogging", "yes");
        sb.AppendLine();

        if (o.OfferDesktopShortcut)
        {
            sb.AppendLine("[Tasks]");
            sb.AppendLine($"Name: \"desktopicon\"; Description: \"Create a &desktop shortcut\"; GroupDescription: \"Additional shortcuts:\"{(o.DesktopShortcutCheckedByDefault ? "" : "; Flags: unchecked")}");
            sb.AppendLine();
        }

        sb.AppendLine("[Files]");
        sb.AppendLine($"Source: \"{Param(input.SourceDirectory.TrimEnd('\\', '/') + "\\*")}\"; DestDir: \"{{app}}\"; Flags: ignoreversion recursesubdirs createallsubdirs");
        sb.AppendLine();

        sb.AppendLine("[Icons]");
        sb.AppendLine($"Name: \"{{autoprograms}}\\{Param(shortcut)}\"; Filename: \"{{app}}\\{Param(input.ExecutableFileName)}\"; WorkingDir: \"{{app}}\"");
        if (o.OfferDesktopShortcut)
            sb.AppendLine($"Name: \"{{autodesktop}}\\{Param(shortcut)}\"; Filename: \"{{app}}\\{Param(input.ExecutableFileName)}\"; WorkingDir: \"{{app}}\"; Tasks: desktopicon");
        sb.AppendLine();

        if (o.OfferLaunchAfterInstall)
        {
            sb.AppendLine("[Run]");
            sb.AppendLine($"Filename: \"{{app}}\\{Param(input.ExecutableFileName)}\"; Description: \"Launch {Param(name)}\"; Flags: nowait postinstall skipifsilent");
            sb.AppendLine();
        }

        // Inno removes everything it installed; also remove the folder itself if the app left nothing behind.
        sb.AppendLine("[UninstallDelete]");
        sb.AppendLine("Type: dirifempty; Name: \"{app}\"");
        return sb.ToString();

        void Directive(string key, string value) => sb.Append(key).Append('=').AppendLine(value);
    }

    /// <summary>Removes control characters (incl. line breaks, which would start new directives) and trims.</summary>
    internal static string Clean(string? value, string fallback)
    {
        var cleaned = new string((value ?? "").Where(c => !char.IsControl(c)).ToArray()).Trim();
        return cleaned.Length == 0 ? fallback : cleaned;
    }

    /// <summary>Escapes free text for a [Setup] directive value: a literal "{" is written "{{".</summary>
    internal static string Inno(string value) => Clean(value, "").Replace("{", "{{");

    /// <summary>Escapes free text inside a quoted section parameter: braces doubled, quotes doubled.</summary>
    internal static string Param(string value) => Inno(value).Replace("\"", "\"\"");

    /// <summary>"1.2.3-beta" → "1.2.3.0"; null when the version has no numeric prefix.</summary>
    internal static string? NumericVersion(string version)
    {
        var m = NumericPrefix().Match(version);
        if (!m.Success) return null;
        var parts = m.Value.Split('.').Select(p => int.TryParse(p, out var n) ? Math.Min(n, 65535) : 0).ToList();
        while (parts.Count < 4) parts.Add(0);
        return string.Join('.', parts.Take(4));
    }

    [GeneratedRegex(@"^\d+(\.\d+){0,3}")]
    private static partial Regex NumericPrefix();
}
