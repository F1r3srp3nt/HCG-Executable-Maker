using System.Buffers.Binary;

namespace HCG.ExecutableMaker.Packaging.Icons;

public enum IconFormat
{
    Unknown,
    Png,
    Ico,
    Icns,
}

public sealed record IconImage(int Width, int Height, string Encoding);

public sealed record IconInfo(IconFormat Format, IReadOnlyList<IconImage> Images, bool? HasTransparency, IReadOnlyList<string> Warnings, IReadOnlyList<string> Errors)
{
    public IconImage? Largest => Images.OrderByDescending(i => (long)i.Width * i.Height).FirstOrDefault();
    public bool IsValid => Errors.Count == 0 && Images.Count > 0;
}

/// <summary>Reads icon headers (PNG, ICO, ICNS) without decoding pixels, and produces user-facing validation feedback.</summary>
public static class IconInspector
{
    public const int RecommendedMinimum = 512;
    public const int WindowsMaximum = 256;

    public static IconInfo Inspect(string path)
    {
        byte[] data;
        try { data = File.ReadAllBytes(path); }
        catch (IOException ex) { return new IconInfo(IconFormat.Unknown, [], null, [], [$"Could not read file: {ex.Message}"]); }
        return Inspect(data);
    }

    public static IconInfo Inspect(byte[] data)
    {
        var errors = new List<string>();
        var images = new List<IconImage>();
        bool? alpha = null;
        IconFormat format;

        if (IsPng(data))
        {
            format = IconFormat.Png;
            if (TryReadPngHeader(data, out var w, out var h, out var hasAlpha)) { images.Add(new IconImage(w, h, "PNG")); alpha = hasAlpha; }
            else errors.Add("PNG header is invalid.");
        }
        else if (data.Length >= 6 && BinaryPrimitives.ReadUInt16LittleEndian(data) == 0 && BinaryPrimitives.ReadUInt16LittleEndian(data.AsSpan(2)) == 1)
        {
            format = IconFormat.Ico;
            var count = BinaryPrimitives.ReadUInt16LittleEndian(data.AsSpan(4));
            if (count == 0 || 6 + count * 16 > data.Length) errors.Add("ICO directory is invalid.");
            else
            {
                for (var i = 0; i < count; i++)
                {
                    var e = data.AsSpan(6 + i * 16, 16);
                    var w = e[0] == 0 ? 256 : e[0];
                    var h = e[1] == 0 ? 256 : e[1];
                    var bpp = BinaryPrimitives.ReadUInt16LittleEndian(e[6..]);
                    var size = BinaryPrimitives.ReadInt32LittleEndian(e[8..]);
                    var offset = BinaryPrimitives.ReadInt32LittleEndian(e[12..]);
                    if (offset < 0 || size <= 0 || (long)offset + size > data.Length) { errors.Add($"ICO image {i + 1} points outside the file."); continue; }
                    var payload = data.AsSpan(offset, size);
                    var isPng = IsPng(payload);
                    if (isPng && TryReadPngHeader(payload, out var pw, out var ph, out var pa)) { w = pw; h = ph; alpha = (alpha ?? false) || pa; }
                    else if (bpp == 32) alpha = true;
                    images.Add(new IconImage(w, h, isPng ? "PNG" : $"BMP {bpp}-bit"));
                }
            }
        }
        else if (data.Length >= 8 && data[0] == 'i' && data[1] == 'c' && data[2] == 'n' && data[3] == 's')
        {
            format = IconFormat.Icns;
            foreach (var (type, payload) in ReadIcnsElements(data, errors))
            {
                if (IsPng(payload) && TryReadPngHeader(payload, out var w, out var h, out var a)) { images.Add(new IconImage(w, h, $"PNG ({type})")); alpha = (alpha ?? false) || a; }
                else if (IcnsLegacySizes.TryGetValue(type, out var s)) images.Add(new IconImage(s, s, $"legacy ({type})"));
            }
            if (images.Count == 0 && errors.Count == 0) errors.Add("No recognizable images found in ICNS file.");
        }
        else
        {
            format = IconFormat.Unknown;
            errors.Add("Unsupported file type. Use PNG, ICO, or ICNS.");
        }

        var warnings = new List<string>();
        if (images.Count > 0)
        {
            var largest = images.OrderByDescending(i => i.Width * i.Height).First();
            if (largest.Width != largest.Height)
                warnings.Add($"Icon is not square ({largest.Width}×{largest.Height}). It will be centered on a transparent square canvas, never stretched.");
            var edge = Math.Max(largest.Width, largest.Height);
            if (edge < RecommendedMinimum)
                warnings.Add($"Largest image is {edge}px. At least {RecommendedMinimum}px (ideally 1024px) is recommended for sharp macOS icons; larger sizes will not be generated by upscaling.");
            if (alpha == false)
                warnings.Add("Icon has no transparency. Platform icons usually expect a transparent background.");
        }
        return new IconInfo(format, images, alpha, warnings, errors);
    }

    internal static readonly Dictionary<string, int> IcnsLegacySizes = new()
    {
        ["is32"] = 16, ["il32"] = 32, ["ih32"] = 48, ["it32"] = 128, ["ICN#"] = 32, ["icl8"] = 32,
    };

    internal static IEnumerable<(string Type, byte[] Payload)> ReadIcnsElements(byte[] data, List<string>? errors = null)
    {
        var declared = BinaryPrimitives.ReadUInt32BigEndian(data.AsSpan(4));
        var end = (int)Math.Min(declared, (uint)data.Length);
        var offset = 8;
        var list = new List<(string, byte[])>();
        while (offset + 8 <= end)
        {
            var type = System.Text.Encoding.ASCII.GetString(data, offset, 4);
            var len = (int)BinaryPrimitives.ReadUInt32BigEndian(data.AsSpan(offset + 4));
            if (len < 8 || offset + len > end) { errors?.Add("ICNS element length is invalid."); break; }
            list.Add((type, data.AsSpan(offset + 8, len - 8).ToArray()));
            offset += len;
        }
        return list;
    }

    internal static bool IsPng(ReadOnlySpan<byte> d) =>
        d.Length >= 8 && d[0] == 0x89 && d[1] == 'P' && d[2] == 'N' && d[3] == 'G' && d[4] == 0x0D && d[5] == 0x0A && d[6] == 0x1A && d[7] == 0x0A;

    internal static bool TryReadPngHeader(ReadOnlySpan<byte> d, out int width, out int height, out bool hasAlpha)
    {
        width = height = 0;
        hasAlpha = false;
        if (d.Length < 33 || d[12] != 'I' || d[13] != 'H' || d[14] != 'D' || d[15] != 'R') return false;
        width = BinaryPrimitives.ReadInt32BigEndian(d[16..]);
        height = BinaryPrimitives.ReadInt32BigEndian(d[20..]);
        var colorType = d[25];
        hasAlpha = colorType is 4 or 6;
        if (!hasAlpha)
        {
            // A tRNS chunk also provides transparency.
            var offset = 8;
            while (offset + 8 <= d.Length)
            {
                var len = BinaryPrimitives.ReadInt32BigEndian(d[offset..]);
                var type = d.Slice(offset + 4, 4);
                if (type.SequenceEqual("tRNS"u8)) { hasAlpha = true; break; }
                if (type.SequenceEqual("IDAT"u8) || len < 0) break;
                offset += 12 + len;
            }
        }
        return width > 0 && height > 0;
    }
}
