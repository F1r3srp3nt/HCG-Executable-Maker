using System.Text.RegularExpressions;
using HCG.ExecutableMaker.Core;
using HCG.ExecutableMaker.Packaging.Signing;
using HCG.ExecutableMaker.Porting.Apple;
using HCG.Impactor.Diagnostics;
using HCG.Impactor.Signing;

namespace HCG.Impactor.MacOS;

public sealed record ProvisioningRequest
{
    public required string BundleIdentifier { get; init; }
    /// <summary>Apple Developer team ID (10 characters) the App ID and profile are created in.</summary>
    public required string TeamId { get; init; }
    /// <summary>Entitlements the app needs; Xcode enables the matching capabilities on the App ID.</summary>
    public IReadOnlyDictionary<string, object> Entitlements { get; init; } = new Dictionary<string, object>();
    public string MinimumIos { get; init; } = "16.0";
    /// <summary>Also register the connected device(s) with the team (-allowProvisioningDeviceRegistration).</summary>
    public bool RegisterConnectedDevices { get; init; }
    /// <summary>
    /// Optional App Store Connect API key (.p8 path, key ID, issuer ID) for xcodebuild's -authenticationKey* options —
    /// used instead of the Xcode account. The key file is read by xcodebuild only; HCG never copies or stores it.
    /// </summary>
    public (string KeyPath, string KeyId, string IssuerId)? ApiKey { get; init; }
}

public sealed record ProvisioningResult
{
    public bool Succeeded { get; init; }
    /// <summary>The profile Xcode used or created ("iOS Team Provisioning Profile: …"), from xcodebuild's output.</summary>
    public string? ProfileName { get; init; }
    public string? ProfileUuid { get; init; }
    public string? SigningIdentity { get; init; }
    /// <summary>Profile files that appeared or changed in Xcode's profile folders.</summary>
    public IReadOnlyList<string> NewProfiles { get; init; } = [];
    public string? StubProject { get; init; }
    public string? LogPath { get; init; }
    public Diagnosis? Failure { get; init; }
    public IReadOnlyList<string> Log { get; init; } = [];
}

/// <summary>
/// Creates the App ID and a Development provisioning profile for an app with Apple's supported automatic signing,
/// using the Apple Account already signed in to Xcode (or an App Store Connect API key): HCG writes a throwaway stub
/// iOS project with the app's bundle identifier and entitlements and builds it once with
/// <c>xcodebuild -allowProvisioningUpdates [-allowProvisioningDeviceRegistration]</c>. Xcode registers the App ID,
/// enables the capabilities, registers the connected device and downloads the profile — exactly what Xcode's
/// "Automatically manage signing" does — so you do not create a temporary project yourself. The stub is never
/// installed; no certificate is revoked; existing profiles are not deleted. Needs your explicit approval each time,
/// because it changes your Apple Developer account (adds an App ID / device / profile).
/// </summary>
public sealed partial class XcodeProvisioningAssistant(IProcessRunner runner, string workRoot, ProvisioningProfileStore? profiles = null)
{
    public const string TargetName = "HCGProvisioningStub";

    public bool IsAvailable => OperatingSystem.IsMacOS() && File.Exists("/usr/bin/xcrun");

    /// <summary>Writes the stub project; returns its folder. Exposed for tests and for showing the user what will be built.</summary>
    public static string WriteStubProject(string folder, ProvisioningRequest r)
    {
        Directory.CreateDirectory(Path.Combine(folder, "Sources"));
        File.WriteAllText(Path.Combine(folder, "Sources", "StubApp.swift"), """
            // Generated by HCG Impactor's provisioning assistant. This stub exists only so Xcode's automatic signing can
            // register the App ID and create a provisioning profile. It is never installed or distributed.
            import SwiftUI

            @main
            struct HCGProvisioningStub: App {
                var body: some Scene {
                    WindowGroup { Text("HCG provisioning stub — not an app") }
                }
            }

            """);
        var spec = new XcodeProjectWriter.Spec
        {
            TargetName = TargetName,
            DisplayName = "HCG Provisioning Stub",
            BundleId = r.BundleIdentifier,
            Version = "1.0",
            BuildNumber = 1,
            DeploymentTarget = r.MinimumIos,
            SourceFolder = "Sources",
            SwiftFiles = ["StubApp.swift"],
        };
        var proj = Path.Combine(folder, TargetName + ".xcodeproj");
        Directory.CreateDirectory(Path.Combine(proj, "xcshareddata", "xcschemes"));
        File.WriteAllText(Path.Combine(proj, "project.pbxproj"), XcodeProjectWriter.Pbxproj(spec));
        File.WriteAllText(Path.Combine(proj, "xcshareddata", "xcschemes", TargetName + ".xcscheme"), XcodeProjectWriter.Scheme(spec));
        if (r.Entitlements.Count > 0)
            File.WriteAllText(Path.Combine(folder, TargetName + ".entitlements"), PlistXmlWriter.Write(StubEntitlements(r)));
        return folder;
    }

    /// <summary>The entitlements the stub requests: the app's own, minus identity keys Xcode fills in itself.</summary>
    internal static IReadOnlyDictionary<string, object> StubEntitlements(ProvisioningRequest r) =>
        r.Entitlements.Where(kv => kv.Key is not ("application-identifier" or "com.apple.developer.team-identifier" or "get-task-allow"))
            .ToDictionary(kv => kv.Key, kv => EntitlementComposer.Rewrite(kv.Value, null, r.TeamId, null, null));

    /// <summary>The exact xcodebuild arguments (shown to the user before they approve).</summary>
    public static IReadOnlyList<string> Arguments(string folder, ProvisioningRequest r)
    {
        var a = new List<string>
        {
            "xcodebuild", "-project", Path.Combine(folder, TargetName + ".xcodeproj"), "-scheme", TargetName, "-configuration", "Debug",
            "-destination", "generic/platform=iOS", "-derivedDataPath", Path.Combine(folder, "DerivedData"),
            "-allowProvisioningUpdates",
        };
        if (r.RegisterConnectedDevices) a.Add("-allowProvisioningDeviceRegistration");
        if (r.ApiKey is { } k) a.AddRange(["-authenticationKeyPath", k.KeyPath, "-authenticationKeyID", k.KeyId, "-authenticationKeyIssuerID", k.IssuerId]);
        a.AddRange([$"DEVELOPMENT_TEAM={r.TeamId}", "CODE_SIGN_STYLE=Automatic", $"PRODUCT_BUNDLE_IDENTIFIER={r.BundleIdentifier}"]);
        if (r.Entitlements.Count > 0) a.Add($"CODE_SIGN_ENTITLEMENTS={Path.Combine(folder, TargetName + ".entitlements")}");
        a.Add("build");
        return a;
    }

    public async Task<ProvisioningResult> CreateAsync(ProvisioningRequest r, IProgress<string>? progress, CancellationToken ct)
    {
        var log = new List<string>();
        void Say(string s) { log.Add(s); progress?.Report(s); }
        if (!IsAvailable) return new ProvisioningResult { Failure = InstallDiagnostics.Diagnose("", toolMissing: true), Log = log };
        if (!BundleIds.IsValid(r.BundleIdentifier) || !TeamRegex().IsMatch(r.TeamId))
            return new ProvisioningResult { Failure = new Diagnosis(DiagnosisKind.Unknown, "Invalid request", "The bundle identifier or team ID is not valid.", "Use a reverse-DNS bundle ID and the 10-character team ID shown in Certificates."), Log = log };

        var folder = Path.Combine(workRoot, "provisioning", $"{r.BundleIdentifier}-{DateTime.UtcNow:yyyyMMdd-HHmmss}");
        WriteStubProject(folder, r);
        Say($"Stub project: {folder}");
        var before = Snapshot();
        var args = Arguments(folder, r);
        Say("$ xcrun " + string.Join(' ', args.Select(x => x.Contains(' ') ? $"\"{x}\"" : x)));
        var text = new System.Text.StringBuilder();
        var gate = new object();
        var result = await runner.RunAsync(new ProcessSpec { Executable = "/usr/bin/xcrun", Arguments = args, Timeout = TimeSpan.FromMinutes(20), WorkingDirectory = folder },
            (_, line) =>
            {
                lock (gate) text.AppendLine(line);
                if (line.Contains("Signing Identity:", StringComparison.Ordinal) || line.Contains("Provisioning Profile:", StringComparison.Ordinal)
                    || line.Contains("error:", StringComparison.Ordinal) || line.Contains("BUILD ", StringComparison.Ordinal))
                    Say(InstallDiagnostics.Redact(line.Trim()));
            }, ct).ConfigureAwait(false);
        var output = text.ToString();
        var logPath = Path.Combine(folder, "xcodebuild.log");
        await File.WriteAllTextAsync(logPath, InstallDiagnostics.Redact(output), CancellationToken.None).ConfigureAwait(false);
        var changed = Snapshot().Where(kv => !before.TryGetValue(kv.Key, out var t) || t != kv.Value).Select(kv => kv.Key).ToList();
        var profile = ProfileLine().Match(output);
        var identity = IdentityLine().Match(output);
        // The build only has to get past signing; a stub compile problem after a profile was obtained still counts.
        var gotProfile = profile.Success || changed.Count > 0;
        if (!result.Succeeded && !gotProfile)
            return new ProvisioningResult { Failure = ProvisioningDiagnostics.Diagnose(output, result.Cancelled, result.TimedOut), StubProject = folder, LogPath = logPath, Log = log };
        Say(profile.Success ? $"Profile: {profile.Groups["name"].Value}" : $"{changed.Count} profile file(s) added or updated.");
        TryDelete(Path.Combine(folder, "DerivedData"));
        return new ProvisioningResult
        {
            Succeeded = true,
            ProfileName = profile.Success ? profile.Groups["name"].Value : null,
            ProfileUuid = profile.Success && profile.Groups["uuid"].Success ? profile.Groups["uuid"].Value : null,
            SigningIdentity = identity.Success ? identity.Groups["name"].Value : null,
            NewProfiles = changed,
            StubProject = folder,
            LogPath = logPath,
            Log = log,
        };
    }

    private Dictionary<string, DateTime> Snapshot()
    {
        var home = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
        var folders = new[]
        {
            profiles?.InstallFolder ?? Path.Combine(home, "Library", "Developer", "Xcode", "UserData", "Provisioning Profiles"),
            Path.Combine(home, "Library", "MobileDevice", "Provisioning Profiles"),
        };
        return folders.Distinct().Where(Directory.Exists).SelectMany(Directory.EnumerateFiles).Where(ProvisioningProfileStore.IsProfileFile)
            .ToDictionary(f => f, File.GetLastWriteTimeUtc);
    }

    private static void TryDelete(string dir)
    {
        try { if (Directory.Exists(dir)) Directory.Delete(dir, true); } catch (IOException) { } catch (UnauthorizedAccessException) { }
    }

    [GeneratedRegex(@"^[A-Z0-9]{10}$")] private static partial Regex TeamRegex();
    [GeneratedRegex(@"Provisioning Profile:\s+""(?<name>[^""]+)""(?:\s+\((?<uuid>[0-9A-Fa-f-]{36})\))?")] private static partial Regex ProfileLine();
    [GeneratedRegex(@"Signing Identity:\s+""(?<name>[^""]+)""")] private static partial Regex IdentityLine();
}

/// <summary>Translates xcodebuild automatic-provisioning failures into explanations and next steps.</summary>
public static class ProvisioningDiagnostics
{
    private static readonly (Regex Pattern, string Title, string Explanation, string Remedy)[] Rules =
    [
        (new(@"No Accounts|No account for team|Add a new account in (the )?Accounts", RegexOptions.IgnoreCase),
            "Xcode is not signed in to this team",
            "xcodebuild found no Apple Account for the team in Xcode's settings, so it cannot create profiles.",
            "Open Xcode › Settings › Accounts, sign in with the Apple Account of the team, then try again (or use an App Store Connect API key)."),
        (new(@"cannot be registered to your development team|is not available\. Please enter a different string|already (in use|exists).*identifier", RegexOptions.IgnoreCase),
            "Bundle identifier belongs to another team",
            "Apple refused to register the App ID because this bundle identifier is already registered by a different team.",
            "Use the team that owns the identifier, or a different bundle identifier."),
        (new(@"team has no devices|no devices from which to generate|register (a|your) device", RegexOptions.IgnoreCase),
            "No registered device",
            "A Development profile needs at least one registered device, and none was registered or connected.",
            "Connect and unlock the iPhone (trusted, Developer Mode on) and run again with device registration, or register its UDID at developer.apple.com › Devices."),
        (new(@"requires a development team|Select a development team", RegexOptions.IgnoreCase),
            "No team selected",
            "The build had no development team.",
            "Choose the team (10-character ID) the profile should belong to."),
        (new(@"maximum number of|free provisioning|Personal development teams.*do not support|does not support the .* capability|capability.*not (supported|available)", RegexOptions.IgnoreCase),
            "The team cannot provide this capability",
            "The App ID needs a capability the team does not offer (for example a Personal Team, or a capability that needs Apple's approval), or the free-account app limit was reached.",
            "Remove the entitlement from the app, use a paid Apple Developer Program team, or request the capability from Apple."),
        (new(@"No signing certificate|certificate.*(not found|missing)|Revoked|has been revoked", RegexOptions.IgnoreCase),
            "No usable signing certificate",
            "Xcode found no valid Apple Development certificate with its private key for this team.",
            "Xcode › Settings › Accounts › Manage Certificates › + › Apple Development. HCG does not revoke or replace certificates."),
        (new(@"Communication with Apple failed|network|could not connect|The Internet connection appears to be offline", RegexOptions.IgnoreCase),
            "Could not reach Apple",
            "Xcode could not contact Apple's developer services.",
            "Check the network connection and try again."),
        (new(@"No profiles for .* were found|doesn't match the entitlements|Provisioning profile .* doesn't", RegexOptions.IgnoreCase),
            "Xcode could not create a matching profile",
            "Automatic signing ran but no profile matching the bundle identifier and entitlements could be created.",
            "Open the log: the first error names the missing capability or device. Then fix it at developer.apple.com and try again."),
    ];

    public static Diagnosis Diagnose(string output, bool cancelled = false, bool timedOut = false)
    {
        var red = InstallDiagnostics.Redact(output);
        if (cancelled) return new Diagnosis(DiagnosisKind.Cancelled, "Cancelled", "Profile creation was cancelled.", "Nothing was installed. Run it again when ready.") { RawRedacted = red };
        foreach (var (p, t, e, r) in Rules)
            if (p.Match(red) is { Success: true } m)
                return new Diagnosis(DiagnosisKind.ProvisioningFailed, t, e, r) { Evidence = Line(red, m.Index), RawRedacted = red };
        return timedOut
            ? new Diagnosis(DiagnosisKind.TimedOut, "Timed out", "xcodebuild did not finish in time.", "Try again; the first automatic provisioning can take several minutes.") { RawRedacted = red }
            : new Diagnosis(DiagnosisKind.ProvisioningFailed, "Profile creation failed", "xcodebuild reported an error HCG does not recognise. The original output is below.",
                "Open the log and look for the first \"error:\" line.") { RawRedacted = red, Evidence = red.Split('\n').FirstOrDefault(l => l.Contains("error", StringComparison.OrdinalIgnoreCase))?.Trim() };
    }

    private static string Line(string text, int index)
    {
        var start = text.LastIndexOf('\n', Math.Max(0, index - 1)) + 1;
        var end = text.IndexOf('\n', index);
        return text[start..(end < 0 ? text.Length : end)].Trim();
    }
}
